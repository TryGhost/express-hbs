'use strict';

var generateId = require('./generate-id');

var ID_LENGTH = 8;
var ID_PREFIX = '__aSyNcId__';

// NOTE: We must include a character which is escaped by Handlebars in the "async id"
// This is so that when using an async helper "inline", such as {{asyncHelper "foo"}}
// the content is correctly escaped depending on whether double or triple braces.
var ID_ESCAPED_STRING = '<_';

var ID_SUFFIX = '__';

function createId() {
  return ID_PREFIX + ID_ESCAPED_STRING + generateId(ID_LENGTH) + ID_SUFFIX;
}

function resolve(cache, fn, context) {
  var id = createId();
  cache[id] = new Promise(function (passed, failed) {
    try {
      fn(context, function (res) {
        passed(res);
      });
    } catch (error) {
      failed(error);
    }
  });
  return id;
}

// Like resolve, but `fn` takes no callback: it returns the result or a thenable.
// A sync throw or a rejection fails the render. null/undefined render as an empty
// string, matching how Handlebars renders sync helpers.
function resolvePromise(cache, fn) {
  var id = createId();
  var promise = new Promise(function (passed) {
    passed(fn());
  }).then(function (res) {
    return res === undefined || res === null ? '' : res;
  });
  // done() reports the rejection; this stops Node flagging it as unhandled when the
  // render fails before done() attaches its handlers.
  promise.catch(function () {});
  cache[id] = promise;
  return id;
}

// cache is an object where the keys are cache keys and values are promises. See above.
function done(cache, callback) {
  return Promise.all(Object.values(cache))
    .then(function (values) {
      var resolvedCache = {};
      var keys = Object.keys(cache);
      values.forEach(function (value, index) {
        resolvedCache[keys[index]] = value;
      });
      callback(null, resolvedCache);
    })
    .catch(function (error) {
      // Callers use `if (err)`, so a falsy reason (e.g. `Promise.reject()`) would
      // otherwise be treated as success with no values.
      if (!error) {
        error = new Error('Async helper failed with ' + String(error));
      }
      callback(error);
    });
}

function hasResolvers(text, cache, escape) {
  // NOTE: We specifically search the text for the ID_PREFIX **NOT** including the escapable character
  // This is because that character can be escaped in the text, and lead us to not finding unresolved
  // async helper outputs.
  if (text.indexOf(ID_PREFIX) < 0) {
    return false;
  }
  if (!cache) {
    return true;
  }
  // Only report IDs that were actually generated by an async helper. The prefix can also
  // appear in user-supplied data, which must never be treated as an unresolved helper.
  return Object.keys(cache).some(function (id) {
    return text.indexOf(id) >= 0 || (escape && text.indexOf(escape(id)) >= 0);
  });
}

module.exports = {
  done: done,
  hasResolvers: hasResolvers,
  resolve: resolve,
  resolvePromise: resolvePromise,
};
